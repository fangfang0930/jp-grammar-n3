def parse_raw(text: str) -> list[dict]:
    # Drop watermarks / page headers noise.
    text = re.sub(r"欢迎关注[^\n]*", "", text)
    text = re.sub(r"===== PAGE \d+ =====\n?", "\n", text)
    text = re.sub(r"\n{3,}", "\n\n", text)

    # Known pattern keys sorted longest-first for greedy match.
    keys = sorted(GLOSS.keys(), key=len, reverse=True)
    # Build regex that finds pattern labels at line starts.
    rows: list[tuple[str, str]] = []
    # Flatten lines while keeping pattern on its line when possible.
    lines = [ln.rstrip() for ln in text.splitlines()]
    i = 0
    current_key: str | None = None
    buf: list[str] = []

    def flush():
        nonlocal current_key, buf
        if current_key and buf:
            jp = clean_jp("".join(buf))
            if jp:
                rows.append((current_key, jp))
        current_key = None
        buf = []

    while i < len(lines):
        line = lines[i].strip()
        if not line or re.fullmatch(r"\d+", line) or line in {
            "文型",
            "例文",
            "条",
            "件",
            "条件",
            "逆接条件",
            "范",
            "围",
            "限定",
            "非限定",
            "否",
            "定",
            "否定",
            "部分否定",
            "心",
            "情",
            "强调心情",
            "无 法 抑 制",
            "的心情",
            "时间/场",
            "合",
            "程度/比",
            "较",
            "对比",
            "可能/难",
            "易",
            "目的",
            "经验",
            "有意图的",
            "行为的开",
            "始・结果",
            "样子",
            "倾向",
            "愿望",
            "意志",
            "劝诱、",
            "要求、劝",
            "告",
            "推量",
            "对象",
            "起点、",
            "终点、界",
            "限、范围",
            "附带状",
            "态、非附",
            "带状态",
            "进行",
            "评价的",
            "视角",
            "标准",
            "感叹",
        }:
            i += 1
            continue
        if re.match(r"^\d+\s", line) and not any(k in line for k in keys):
            # Section headers like "1 时间的前后"
            i += 1
            continue
        if line.startswith("15 类") or line.startswith("20 类"):
            i += 1
            continue

        matched = None
        for key in keys:
            if line == key or line.startswith(key + " ") or line.startswith(key + "\t"):
                matched = key
                rest = line[len(key) :].strip()
                break
            # pattern alone on line, example on following lines
            if line == key:
                matched = key
                rest = ""
                break

        if matched:
            flush()
            current_key = matched
            if rest:
                buf.append(rest)
            i += 1
            continue

        # continuation of example
        if current_key:
            # New bare pattern line without example yet
            if line in keys:
                flush()
                current_key = line
                buf = []
                i += 1
                continue
            buf.append(line)
        i += 1
    flush()
    return rows


def headline_from_example(pattern: str, example: str) -> str:
    # Prefer a short chunk containing the grammar surface form.
    surface = GLOSS.get(pattern, (pattern, "", ""))[0].replace("～", "").split("／")[0]
    surface = re.sub(r"[＜＞（）()].*$", "", surface)
    # Find a clause around the pattern.
    for part in re.split(r"[。！？]", example):
        if surface and surface in part:
            chunk = part.strip("、， ")
            if 4 <= len(chunk) <= 22:
                return chunk
            return chunk[:18] + ("…" if len(chunk) > 18 else "")
    return GLOSS.get(pattern, (pattern, "", ""))[0]


