function headlineFromExample(key: string, example: string) {
  const surface = GLOSS[key][0].replace("～", "").replace(/[＜＞（）].*$/, "")
  for (const part of example.split(/[。！？]/)) {
    if (surface && part.includes(surface)) {
      const chunk = part.replace(/^[、，\s]+|[、，\s]+$/g, "")
      if (chunk.length >= 4 && chunk.length <= 22) return chunk
      return chunk.length > 18 ? `${chunk.slice(0, 18)}…` : chunk
    }
  }
  return GLOSS[key][0]
}

function parseRaw(text: string) {
  text = text
    .replace(/欢迎关注[^\n]*/g, "")
    .replace(/===== PAGE \d+ =====\n?/g, "\n")
  const keys = Object.keys(GLOSS).sort((a, b) => b.length - a.length)
  const lines = text.split(/\r?\n/).map((l) => l.trimEnd())
  const rows: Array<[string, string]> = []
  let current: string | null = null
  let buf: string[] = []

  const flush = () => {
    if (current && buf.length) {
      const jp = cleanJp(buf.join(""))
      if (jp) rows.push([current, jp])
    }
    current = null
    buf = []
  }

  for (const raw of lines) {
    const line = raw.trim()
    if (!line || /^\d+$/.test(line) || SKIP.has(line)) continue
    if (/^\d+\s/.test(line) && !keys.some((k) => line.includes(k))) continue
    if (line.startsWith("15 类") || line.startsWith("20 类")) continue

    let matched: string | null = null
    let rest = ""
    for (const key of keys) {
      if (line === key || line.startsWith(`${key} `) || line.startsWith(`${key}\t`)) {
        matched = key
        rest = line.slice(key.length).trim()
        break
      }
    }
    if (matched) {
      flush()
      current = matched
      if (rest) buf.push(rest)
      continue
    }
    if (current) {
      if (keys.includes(line)) {
        flush()
        current = line
        buf = []
        continue
      }
      buf.push(line)
    }
  }
  flush()
  return rows
}

